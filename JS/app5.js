function Vezes() {

    let vezes = prompt("Digite a quantidade de vezes")
    vezes = Number(vezes)
    let i = 1;
    while (i <= vezes) {
        if (i == 67) {
            alert("Sixxxxxxxxx seveeeeeeeeennnnnn Aura 9999+🗿🥶");
        } else if (i == 69) {
            alert("kkkkkk meia novi kkkk");
        } else {
            alert(`contei ${i} vez`);
        }
        i = i + 1;
    }
}